export function findSample(id: string | undefined | null): Sample | undefined {
  if (!id) return undefined;
  return SAMPLES.find((s) => s.id === id);
}

/** 入力文がサンプルと完全一致する場合はそのサンプルを返す（デモモード用） */
export function matchSampleByText(text: string): Sample | undefined {
  const norm = (s: string) => s.replace(/\s+/g, "");
  const t = norm(text);
  return SAMPLES.find((s) => norm(s.text) === t);
}
